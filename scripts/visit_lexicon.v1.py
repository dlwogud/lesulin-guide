"""유튜브 댓글용 항목별 감성 — 방문형.

르몽 배달 리뷰로 만든 capstone-review/scripts/lexicon.py 를 방문형으로 옮긴 것입니다.
옮기면서 바꾼 것:

 1. 항목 교체 — 배달(기사·배송·도착)을 빼고 대기·분위기를 넣었습니다.
    방문형에서 제일 많이 나오는 불만이 "줄 서서 기다렸다"인데 르몽 사전엔 그 항목이 없습니다.
    실제로 배달 사전을 그대로 돌리면 "사람들 몰려 있어"를 배달 부정으로 잡습니다.
 2. 영상·출연자 감상 제거 — 르몽 리뷰엔 없고 유튜브 댓글엔 절반 가까이 섞여 있습니다.
    "시경씨 맛있게 드시네요"는 식당 평가가 아닙니다. 절 단위로 걸러냅니다.
 3. 방문 경험 판정 추가 — "가보고 싶다"와 "가봤다"를 가릅니다.
    이건 텍스트 분류이지 방문 인증이 아닙니다.

주의: 부분 문자열 매칭이라 어근을 좁게 잡아야 합니다.
 "대기"는 "대기업"에, "조용"은 "조용필"에, "넓"은 "넓은 세상"에 걸립니다.
"""
import re

ASPECTS = {
  "맛":    (r"맛있|맛없|맛은|맛이|맛도|맛만|맛나|맛좋|맛집|풍미|간이|간은|비리|비려|"
            r"짜요|짭|싱겁|느끼하|느끼해|담백|고소|신선|바삭|촉촉|쫄깃|질겨|질김|퍽퍽|"
            r"존맛|꿀맛|딱딱|육즙|잡내|누린내|안\s*익"),
  "양":    (r"양이|양은|양도|양만|푸짐|넉넉|적어|많아|많고|많네|부족|배부|배\s*터|배터|"
            r"가득|실하|두툼|든든|충분|큼직|알차|풍성|듬뿍|수북|어마어마|1인분|일인분"),
  "가격":  (r"가격|가성비|비싸|저렴|혜자|값|돈값|합리적|할인|돈이\s*아깝|이가격|만원|"
            r"착한\s*가격|가격\s*대비"),
  "서비스": (r"친절|불친절|응대|사장님|서비스|요청|챙겨|신경\s*써|사장|이모님|직원|"
            r"반찬\s*리필|리필|들어주|맞춰주|해\s*주신|실수|무뚝뚝|퉁명"),
  # 방문형의 핵심. 배달 사전엔 아예 없던 항목입니다.
  "대기":  (r"웨이팅|줄\s*서|줄서|줄이\s|기다리|기다렸|기다려|기다림|대기(?!업)|오픈런|"
            r"예약|자리\s*없|만석|품절|솔드아웃|재료\s*소진|일찍\s*가|늦게\s*가면|"
            r"번호표|헛걸음|문\s*닫|웨잇"),
  "분위기": (r"분위기|인테리어|시끄럽|조용하|조용해|깨끗|청결|지저분|위생|협소|좁아|좁고|"
            r"넓어|넓고|쾌적|아늑|주차|화장실|냄새\s*배"),
}

POS = (r"맛있|맛나|맛좋|좋아|좋았|좋네|좋습|최고|쵝고|짱|굿|만족|훌륭|깔끔|신선|담백|고소|"
       r"푸짐|넉넉|많아|많고|가득|실하|배부|저렴|가성비|혜자|친절|따뜻|바삭|촉촉|쾌적|아늑|"
       r"또\s*가|또\s*시|재방문|단골|추천|강추|감사|잘\s*먹|잘먹|괜찮|존맛|꿀맛|맛집|JMT|jmt|"
       r"행복|감동|대만족|최애|인정|성공|극락|사랑|미쳤|지렸|깨끗|조용하|넓어|든든")

NEG = (r"맛없|별로|별루|최악|실망|아쉽|아쉬|눅눅|비려|비림|짜게|싱겁|느끼하|느끼해|느끼함|"
       r"불친절|적어|부족|비싸|다신|다시는|구려|질겨|질김|퍽퍽|이상하|이상해|이상함|불편|"
       r"비위|역겨|느글|돈이\s*아깝|환불|잡내|누린내|무뚝뚝|퉁명|시끄럽|지저분|좁아|협소|"
       r"오래\s*기다|한참\s*기다|헛걸음|웨이팅\s*이\s*길|줄이\s*길|너무\s*길")

# 이중부정: 부정 어근 + "-지 않/못" → 중화
DOUBLE = re.compile(
  r"(적|작|많|늦|비싸|짜|싱겁|느끼|비리|질기|눅눅|차갑|부족|이상하|나쁘|길)"
  r"(지|지는|지도)\s*(않|안\s)")

# 가정·우려·희망은 실제 경험이 아님
HYPO = re.compile(r"(까\s*봐|까봐|줄\s*알았|려나|걱정|시키면|시켰더니|뻔했|뻔\s했|"
                  r"겠다|겠네|겠어|고\s*싶|고싶|가\s*봐야|가봐야|가\s*볼|먹어\s*볼)")

# 영상·출연자 감상. 르몽 리뷰엔 없고 유튜브 댓글엔 넘칩니다.
# 이 패턴이 걸린 절은 식당 평가로 쓰지 않습니다.
MEDIA = re.compile(
  r"(영상|편집|촬영|피디|PD|자막|구독|좋아요|알고리즘|채널|업로드|썸네일|화질|"
  r"목소리|노래|콘서트|공연|방송|출연|형님|누님|시경|쯔양|히밥|풍자|정육왕|"
  r"먹방|먹텐|또간집|보면서|보고\s*있|보는데|잘\s*보고|재밌|재미있|웃기|꿀잼)")

# 식당 쪽 단서. MEDIA와 같이 나오면 식당 얘기로 봅니다.
PLACE = re.compile(r"(가게|식당|집이|집은|집에|매장|사장님|이모님|메뉴|반찬|주차|웨이팅|"
                   r"다녀왔|가봤|먹어봤|단골|줄\s*서)")

# 채널 운영자가 직접 다는 고정 댓글. 가게 소개와 협찬 고지라서 방문자 반응이 아닙니다.
# 좋아요가 가장 많아 그냥 두면 대표 근거 자리를 차지합니다.
PROMO = re.compile(
  r"(고정\s*댓글|본\s*영상은|협찬\s*&?\s*광고|유료\s*광고|위치\s*정보|구매\s*정보|"
  r"비즈니스\s*(메일|문의)|업체\s*문의|제휴\s*문의|쿠폰\s*코드|공식\s*홈페이지|"
  r"유튜브\s*검색\s*=|스마트스토어|네이버\s*:\s*http|인스타\s*:\s*http)")


def promo(text):
    return bool(PROMO.search(str(text)))


# 방문 경험을 명시한 댓글만 집계합니다. 방문 인증이 아니라 텍스트 분류입니다.
VISITED = re.compile(
  r"(다녀왔|다녀옴|다녀온|가봤|갔다왔|갔었|갔는데|갔더니|먹어봤|먹고왔|먹었는데|먹었어|"
  r"먹었습니|방문했|방문하|주문했|시켜먹|단골|자주\s*가|자주\s*먹|여러\s*번\s*갔|"
  r"어제\s*갔|오늘\s*갔|지난주\s*갔|몇\s*번\s*갔)")

SPLIT = re.compile(r"[.!?~\n…,]+|\s(?:근데|그런데|다만|하지만|대신|단)\s"
                   r"|(?<=[가-힣])(?:은데|는데|지만|으나)\s*")


def clauses(text):
    return [c.strip() for c in SPLIT.split(str(text)) if len(c.strip()) >= 2]


def visited(text):
    """방문 경험을 명시했는가. 희망형("가보고 싶다")은 제외합니다."""
    t = str(text)
    if not VISITED.search(t):
        return False
    # "안 먹어봤는데", "못 가봤어요" 같은 부정형은 방문이 아닙니다
    if re.search(r"(안|못|아직)\s*(먹어\s*봤|가\s*봤|가봤|먹어봤|다녀왔)", t):
        return False
    return True


# 대기는 일반 감성어로 풀면 틀립니다.
# "단골집을 줄서서 갑니다 ㅠ"에는 '단골'(긍정)이 붙어 있지만 내용은 기다렸다는 말입니다.
# 그래서 대기만은 "기다렸나 / 안 기다렸나"로 직접 읽습니다.
WAIT_POS = re.compile(
  r"(웨이팅\s*(이\s*)?(없|적|짧)|줄\s*(이\s*)?(없|안\s*서|짧)|대기\s*(가\s*)?(없|짧)|"
  r"기다리지\s*않|기다림\s*없|바로\s*(들어|앉|먹|나와)|길지\s*않|안\s*기다)")
WAIT_NEG = re.compile(
  r"(줄\s*서|줄서|줄이|줄\s*섰|웨이팅|대기(?!업)|기다렸|기다림|기다리|오픈런|번호표|"
  r"만석|자리\s*없|품절|솔드아웃|재료\s*소진|헛걸음|못\s*먹|못\s*들어|돌아왔|발길\s*돌)")


def wait_polarity(clause):
    """대기 항목 전용. 기다렸다는 말이면 부정, 안 기다렸다는 말이면 긍정."""
    if WAIT_POS.search(clause):
        return 1
    if WAIT_NEG.search(clause):
        return -1
    return 0


GAP = 12   # 항목어와 감성어가 이보다 멀면 한 덩어리로 보지 않습니다


def polarity(clause):
    """절 하나의 전체 극성. 1=긍정, -1=부정, 0=판단 보류."""
    if HYPO.search(clause):
        return 0
    c = DOUBLE.sub("긍정표현", clause)
    p = len(re.findall(POS, c))
    n = len(re.findall(NEG, c))
    if p and n:                 # 섞인 절은 아래 polarity_near 가 항목별로 다시 가릅니다
        return 0
    if p: return 1
    if n: return -1
    return 0


def polarity_near(clause, apos):
    """섞인 절에서 항목어 위치 apos 에 가장 가까운 감성어를 따릅니다.

    "20년 단골인 집인데 한참 기다렸습니다" — '단골'(긍정)과 '기다'(부정)가 한 절에 있지만,
    대기 항목어는 '기다' 바로 옆입니다. 거리로 가리면 대기 부정이 맞습니다.
    """
    c = DOUBLE.sub("긍정표현", clause)
    dp = min((abs(m.start() - apos) for m in re.finditer(POS, c)), default=10**6)
    dn = min((abs(m.start() - apos) for m in re.finditer(NEG, c)), default=10**6)
    if min(dp, dn) > GAP:        # 둘 다 멀다 — 근거로 쓰기 부적합
        return 0
    if abs(dp - dn) <= 2:        # 거의 같은 거리 — 판단 보류
        return 0
    return 1 if dp < dn else -1


def analyze(text):
    """댓글 하나 → {항목: 극성}. 영상 감상 절은 버립니다."""
    out = {}
    for cl in clauses(text):
        if MEDIA.search(cl) and not PLACE.search(cl):
            continue                                # 출연자·영상 얘기
        if HYPO.search(cl):
            continue
        pol = polarity(cl)
        for a, pat in ASPECTS.items():
            m = re.search(pat, cl)
            if not m:
                continue
            v = wait_polarity(cl) if a == "대기" else (pol if pol else polarity_near(cl, m.start()))
            if v:
                out.setdefault(a, []).append(v)
    return {a: (1 if sum(v) > 0 else -1) for a, v in out.items() if sum(v) != 0}


if __name__ == "__main__":
    tests = [
      ("여긴 평일 낮에가도 직장인들이 점심 식사하던곳이에요 저도 친구들이랑 낮에 가서먹었는데 "
       "전골 구이 다 맛있었고 이모님들 다 친절했어요", {"맛": 1, "서비스": 1}),
      ("20여 년 단골인 일호족발 사러갔다 사람들 몰려 있어 한참 기다렸습니다", {"대기": -1}),
      ("족발은 별로였지만 닭발은 맛있었어요", {"맛": 1}),
      ("시경씨 너무 맛있게드시네용 ㅎㅎ", {}),                      # 출연자 감상
      ("영상 잘 보고 갑니다 구독했어요", {}),                       # 영상 감상
      ("꼭 가볼게요 맛있겠다", {}),                                # 희망형
      ("아직 못 가봤는데 가보고 싶네요", {}),                        # 미방문
      ("주차가 너무 불편해요 자리도 좁고", {"분위기": -1}),
      ("웨이팅이 길지 않아서 좋았어요", {"대기": 1}),
      ("가격도 저렴하고 양도 푸짐했어요 다음에 또 갈게요", {"가격": 1, "양": 1}),
      ("오픈런 해서 들어갔는데 재료 소진으로 못 먹었어요", {}),
    ]
    ok = 0
    for t, want in tests:
        got = analyze(t)
        hit = (got == want) if want == {} else all(got.get(k) == v for k, v in want.items())
        ok += hit
        print(("  OK  " if hit else "  X   ") + t[:52])
        if not hit:
            print("        기대", want, "→ 실제", got)
    print(f"\n{ok}/{len(tests)} 통과")

    print("\n방문 판정:")
    for t in ["어제 다녀왔어요", "가보고 싶어요", "아직 못 가봤어요", "10년 단골입니다",
              "맛있겠다", "저번주에 먹고왔는데 맛있었어요"]:
        print(f"  {'방문' if visited(t) else '  - '}  {t}")
